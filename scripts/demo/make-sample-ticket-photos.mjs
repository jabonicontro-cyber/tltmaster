#!/usr/bin/env node
// Builds the fictional sample ticket photos the demo samples attach to demo tickets (UX13, migration 20261120020900):
// a phone photo of a paper ticket on a desk, every one clearly stamped SAMPLE and "fictional". Two scale tickets for
// aggregate demos and two bills of lading for freight demos. No real company, person, place or number appears.
// Writes src/server/demo/ticket-photo-images.ts (base64 JPEG), so the server needs no image tools or fonts at run time.
//
//   node scripts/demo/make-sample-ticket-photos.mjs
import { writeFileSync } from "node:fs";
import sharp from "sharp";

const W = 800;
const H = 600;

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

function ticketSvg({ title, lines, sign, tilt, tone }) {
  const rows = lines.map(([label, value], i) => {
    const y = 150 + i * 42;
    return `<text x="40" y="${y}" font-size="17" fill="#444">${esc(label)}</text>
      <line x1="200" y1="${y + 6}" x2="440" y2="${y + 6}" stroke="#999" stroke-width="1"/>
      <text x="206" y="${y}" font-size="19" fill="#1d2f6f" font-family="DejaVu Sans Mono, monospace" font-style="italic">${esc(value)}</text>`;
  }).join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <defs>
    <linearGradient id="desk" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${tone[0]}"/><stop offset="1" stop-color="${tone[1]}"/></linearGradient>
    <linearGradient id="paper" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fbf8ef"/><stop offset="1" stop-color="#ece6d6"/></linearGradient>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="120%"><feDropShadow dx="6" dy="8" stdDeviation="8" flood-opacity="0.35"/></filter>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#desk)"/>
  <g transform="translate(160 38) rotate(${tilt} 240 262)" font-family="DejaVu Sans, Arial, sans-serif">
    <rect width="480" height="524" rx="4" fill="url(#paper)" filter="url(#shadow)"/>
    <rect x="0" y="0" width="480" height="64" fill="#e3ddcb"/>
    <text x="40" y="42" font-size="24" font-weight="bold" fill="#222">${esc(title)}</text>
    <text x="40" y="96" font-size="15" fill="#555">Demo company (fictional) · not a real ticket</text>
    ${rows}
    <text x="40" y="${150 + lines.length * 42 + 18}" font-size="17" fill="#444">${esc(sign)}</text>
    <path d="M 250 ${150 + lines.length * 42 + 14} c 20 -26 34 18 52 -6 s 26 -20 40 4 s 30 -12 50 0" stroke="#1d2f6f" stroke-width="2.5" fill="none"/>
    <g transform="translate(240 300) rotate(-24)">
      <rect x="-190" y="-48" width="380" height="96" rx="10" fill="none" stroke="#b42318" stroke-width="7" opacity="0.72"/>
      <text x="0" y="22" text-anchor="middle" font-size="64" font-weight="bold" fill="#b42318" opacity="0.72" letter-spacing="10">SAMPLE</text>
    </g>
  </g>
</svg>`;
}

const PHOTOS = {
  aggregate: [
    ticketSvg({ title: "SCALE TICKET", tilt: -3, tone: ["#6b5d4f", "#4a4036"], sign: "Received by",
      lines: [["Ticket no.", "SAMPLE-0001"], ["Material", "Crushed stone"], ["Gross", "71,240 lb"], ["Tare", "31,860 lb"], ["Net", "19.69 tons"], ["Truck", "Demo 12"]] }),
    ticketSvg({ title: "DELIVERY TICKET", tilt: 2.5, tone: ["#5a6470", "#3b424b"], sign: "Signed on site",
      lines: [["Ticket no.", "SAMPLE-0002"], ["Material", "Washed sand"], ["Net", "18.40 tons"], ["Job", "Demo job site"], ["Time out", "9:42"], ["Truck", "Demo 7"]] }),
  ],
  freight: [
    ticketSvg({ title: "BILL OF LADING", tilt: -2.5, tone: ["#4f5b66", "#343c44"], sign: "Received by",
      lines: [["BOL no.", "SAMPLE-BOL-01"], ["Shipper", "Demo shipper"], ["Consignee", "Demo receiver"], ["Pieces", "18 pallets"], ["Weight", "26,400 lb"], ["Seal", "SAMPLE-55"]] }),
    ticketSvg({ title: "DELIVERY RECEIPT", tilt: 3, tone: ["#6a6052", "#463f35"], sign: "Receiver",
      lines: [["BOL no.", "SAMPLE-BOL-02"], ["Consignee", "Demo receiver"], ["Pieces", "12 pallets"], ["Damage", "None noted"], ["Time in", "13:05"], ["Trailer", "Demo 53-04"]] }),
  ],
};

let out = `// Generated by scripts/demo/make-sample-ticket-photos.mjs: fictional sample ticket photos (UX13), each stamped
// SAMPLE. Do not edit by hand; run the script again to change them.
export const SAMPLE_TICKET_PHOTOS: Record<"aggregate" | "freight", string[]> = {\n`;
for (const [kind, svgs] of Object.entries(PHOTOS)) {
  out += `  ${kind}: [\n`;
  for (const svg of svgs) {
    const jpeg = await sharp(Buffer.from(svg)).jpeg({ quality: 62, mozjpeg: true }).toBuffer();
    console.log(kind, jpeg.length, "bytes");
    out += `    "${jpeg.toString("base64")}",\n`;
  }
  out += "  ],\n";
}
out += "};\n";
writeFileSync(new URL("../../src/server/demo/ticket-photo-images.ts", import.meta.url), out);
